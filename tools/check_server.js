/* サーバー版の確認（版・更新履歴・利用状況・古いサーバー）。
   使い方:  PYTHON=python node tools/check_server.js     （Flask が入った python を PYTHON に）
   一時フォルダへ本体を写してサーバーを起動し、実際のブラウザで確かめる。 */
const { chromium } = require("playwright");
const { spawn, execSync } = require("child_process");
const fs = require("fs"), os = require("os"), path = require("path");
const ROOT = path.resolve(__dirname, "..");
const PY = process.env.PYTHON || "python3";
const PORT = 57841;
let failed = 0;
const ok = (c, m) => { console.log((c ? "  OK  " : "  NG  ") + m); if (!c) failed++; };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

(async () => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "dm-"));
  for (const d of ["app", "web", "config"]) fs.cpSync(path.join(ROOT, d), path.join(tmp, d), { recursive: true, filter: (s) => !s.includes("__pycache__") });
  fs.copyFileSync(path.join(ROOT, "app_build.py"), path.join(tmp, "app_build.py"));
  fs.copyFileSync(path.join(ROOT, "run.py"), path.join(tmp, "run.py"));
  // 別の PC が新しい版を使っている記録（共有の置き場の代わり）
  const shared = path.join(tmp, "shared"); fs.mkdirSync(path.join(shared, "history"), { recursive: true });
  const now = new Date().toISOString().slice(0, 19);
  fs.writeFileSync(path.join(shared, "history", "PC-B@tanaka.json"), JSON.stringify({ key: "PC-B@tanaka", login: "tanaka", pc: "PC-B", version: "9.0.0", lastAt: now, sessions: 3, totalSec: 3600 }));
  fs.writeFileSync(path.join(tmp, "config", "settings.json"), JSON.stringify({ server: { host: "127.0.0.1", port: PORT, open_browser: false }, presence: { dir: shared } }));
  const srv = spawn(PY, ["run.py", "--no-browser"], { cwd: tmp, stdio: "ignore" });
  const browser = await chromium.launch();
  try {
    for (let i = 0; i < 40; i++) { try { if ((await fetch(`http://127.0.0.1:${PORT}/api/health`)).ok) break; } catch (e) {} await sleep(250); }
    const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 } });
    await ctx.addInitScript(() => { try { localStorage.setItem("dm.helpNever", "1"); } catch (e) {} });
    const p = await ctx.newPage();
    const errs = []; p.on("pageerror", (e) => errs.push(e.message));
    await p.goto(`http://127.0.0.1:${PORT}/`);
    console.log("[版の札]");
    await p.waitForSelector("#ver", { timeout: 5000 });
    ok(/v\d+\.\d+\.\d+/.test(await p.locator("#ver").innerText()), "見出しに版の札が出る");
    await p.waitForSelector("#ver .tag--warn", { timeout: 8000 }).catch(() => {});
    ok((await p.locator("#ver").innerText()).includes("新しい版あり"), "ほかの PC が新しい版(9.0.0)を使っていると「新しい版あり」が出る（文字つき）");
    console.log("[更新履歴・利用状況]");
    await p.locator("#ver").click();
    await p.waitForSelector(".log");
    ok((await p.locator(".log").count()) >= 2, "更新履歴が開く");
    ok((await p.locator(".log .tag--ok").count()) === 1, "使用中の版に札が付く");
    await p.screenshot({ path: path.join(tmp, "log.png") });
    await p.locator('[data-tab="use"]').click();
    await p.waitForSelector(".help-table tbody tr");
    const rows = await p.locator(".help-table tbody tr").count();
    ok(rows === 2, `利用状況に 2 台（この PC とほかの PC）が出る（${rows}）`);
    const txt = await p.locator(".vm__body").innerText();
    ok(txt.includes("PC-B") && txt.includes("v9.0.0"), "ほかの PC の版が見える");
    ok(txt.includes("古い版") && txt.includes("使用中"), "状態が文字で出る（古い版／使用中）");
    ok(txt.includes("最新版：v9.0.0"), "最新版が数で比べられている");
    await p.screenshot({ path: path.join(tmp, "use.png") });
    await p.keyboard.press("Escape");
    console.log("[古いサーバー]");
    ok((await p.locator("#stale-bar").count()) === 0, "入れ替え前は警告が出ない");
    fs.appendFileSync(path.join(tmp, "web", "js", "core.js"), "\n// 入れ替わった\n");
    await p.evaluate(() => fetch("api/instance"));   // 控え(2秒)後に再確認させる
    await sleep(2300);
    const st = await (await fetch(`http://127.0.0.1:${PORT}/api/instance`)).json();
    ok(st.stale === true, "プログラムが入れ替わると /api/instance が stale を返す");
    await p.evaluate(() => document.dispatchEvent(new Event("visibilitychange")));
    await p.waitForSelector("#stale-bar", { timeout: 5000 }).catch(() => {});
    ok((await p.locator("#stale-bar").count()) === 1 && (await p.locator("#stale-bar").innerText()).includes("開いてください"), "画面の上に「開き直してください」が出る");
    await p.screenshot({ path: path.join(tmp, "stale.png") });
    ok(errs.length === 0, "コンソールエラーなし" + (errs.length ? " : " + errs.join(" / ") : ""));
    // ---------------- DB（SQLite）を読む ----------------
    console.log("[DB の読み込み]");
    const db = path.join(tmp, "q.sqlite3");
    execSync(`${PY} ${path.join(ROOT, "tools", "make_sample_db.py")} ${db} 1200`, { stdio: "ignore" });
    const p2 = await ctx.newPage();
    const errs2 = []; p2.on("pageerror", (e) => errs2.push(e.message));
    await p2.goto(`http://127.0.0.1:${PORT}/`);
    await p2.locator('.rail-btn[data-id="data"]').click();
    await p2.locator("[data-src]").fill(db);
    await p2.locator("[data-src]").press("Enter");
    await p2.waitForSelector("tbody tr[data-id]", { timeout: 15000 });
    ok((await p2.locator("tbody tr[data-id]").count()) === 200, "場所を入れて Enter で DB が読み込まれる（1 ページ 200 行）");
    let status = await p2.locator("#status").innerText();
    ok(status.includes("品質データ（仕掛）") && /1,[0-9]{3} 件/.test(status), "状態バーに出どころと総件数が出る: " + status.replace(/\s+/g, " ").slice(0, 60));
    ok((await p2.locator("#cta").innerText()).includes("ロットを選ぶ"), "主操作が「① ロットを選ぶ」に変わる");
    await p2.locator("#search").fill("ｓｈｆ");
    await p2.waitForFunction(() => document.querySelectorAll("tbody tr[data-id]").length < 200 && !document.querySelector("#status").innerText.includes("読み込み中"));
    const nSearch = await p2.locator("tbody tr[data-id]").count();
    ok(nSearch > 0 && nSearch < 200, `サーバー側の検索（全角）で絞れる（${nSearch} 行）`);
    await p2.locator("#search").fill("");
    await p2.waitForFunction(() => document.querySelectorAll("tbody tr[data-id]").length === 200);
    await p2.locator('.grid thead th[data-col="数量"]').click();
    await p2.locator('.grid thead th[data-col="数量"]').click();   // 降順
    await p2.waitForFunction(() => { const t = document.querySelector("tbody tr[data-id] td:nth-child(7)"); return t && t.innerText.trim() === "2,000"; });
    ok(true, "並べ替え（降順）がサーバー側で効く（先頭が 2,000）");
    console.log("[ページをまたぐ選択 → 確認画面]");
    await p2.locator("tbody tr[data-id]").nth(0).click();
    const lot1 = await p2.locator("tbody tr.is-selected td:nth-child(2)").innerText();
    await p2.locator('[data-pg="1"]').click();
    await p2.waitForFunction(() => /2 \/ /.test(document.querySelector("#status").innerText));
    await p2.locator("tbody tr[data-id]").nth(1).click({ modifiers: ["Control"] });
    ok((await p2.locator("#status").innerText()).includes("選択 2 件"), "次のページでも選択が残る（2 件）");
    await p2.locator(".pill").first().click();
    ok((await p2.locator("#cta").innerText()).includes("③ 2 件を確認して印刷"), "主操作が「③ 2 件を確認して印刷」");
    await p2.locator("#cta").click();
    await p2.waitForSelector(".preview .sheet");
    ok((await p2.locator(".preview .sheet").count()) === 2, "別ページで選んだ 2 件が、1 件 1 枚で並ぶ");
    ok((await p2.locator(".preview").innerText()).includes(lot1.trim()), "前のページで選んだロットが帳票に入っている（" + lot1.trim() + "）");
    await p2.screenshot({ path: path.join(tmp, "db-preview.png") });
    await p2.keyboard.press("Escape");
    console.log("[ロットでまとめる・再読込]");
    await p2.locator("[data-group]").check();
    await p2.waitForSelector("tr.group-head");
    ok((await p2.locator("tr.group-head").count()) > 0, "ロットでまとめると見出し行が出る");
    await p2.locator("[data-group]").uncheck();
    await p2.locator("[data-refresh]").click();
    await p2.waitForSelector(".toast");
    ok((await p2.locator(".toast").last().innerText()).includes("更新"), "「再読込」の結果が文字で出る");
    await p2.screenshot({ path: path.join(tmp, "db-main.png") });
    console.log("[自動で再接続・サンプルとの行き来]");
    await p2.reload();
    await p2.waitForSelector("tbody tr[data-id]", { timeout: 15000 });
    ok((await p2.locator("#status").innerText()).includes("品質データ"), "開き直すと自動で DB を読み込む");
    await p2.locator('.rail-btn[data-id="data"]').click();
    await p2.locator('[data-sample="standard"]').click();
    await p2.waitForFunction(() => document.querySelector("#status").innerText.includes("サンプル"));
    ok(true, "サンプルを読み込むと表示がサンプルに替わる");
    await p2.locator("[data-clear-sample]").click();
    await p2.waitForFunction(() => document.querySelector("#status").innerText.includes("品質データ"), null, { timeout: 15000 });
    ok(true, "サンプルだけを消すと DB に戻る");
    console.log("[読めないとき]");
    await p2.locator("[data-src]").fill(path.join(tmp, "ない.sqlite3"));
    await p2.locator("[data-src]").press("Enter");
    await p2.waitForSelector(".state--error", { timeout: 15000 });
    const et = await p2.locator(".state--error").innerText();
    ok(et.includes("読み込めませんでした") && et.includes("もう一度"), "失敗の理由と次の操作が出る: " + et.replace(/\s+/g, " ").slice(0, 70));
    ok((await p2.locator("#cta").innerText()).includes("データを読み込む"), "主操作が「① データを読み込む」に戻る");
    ok(errs2.length === 0, "コンソールエラーなし" + (errs2.length ? " : " + errs2.join(" / ") : ""));
    console.log("画像:", tmp);
  } finally { await browser.close(); srv.kill(); }
  console.log(failed ? `\n${failed} 件 NG` : "\nすべて OK");
  process.exit(failed ? 1 : 0);
})();
